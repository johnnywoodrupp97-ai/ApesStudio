def group_doc(code, levels, by_id, extra_top=""):
    title, doc = GROUPS[code]
    number = doc.split("-", 1)[0]
    ls = [e for e in levels if e["group"] == code]
    L = [GENERATED_NOTE, f"# {number} — {title}", ""]
    if extra_top:
        L += [extra_top, ""]
    else:
        L += [INTROS[code], ""]
    L += [f"**{len(ls)} levels.** Standards: [00 — Level Design & Blender Standards](00-level-design-standards.md) · metrics: [02](02-metrics-and-gym.md) · kits: [10](10-modular-kits.md).", ""]
    img = OUT / "images" / f"{GROUPS[code][1][3:-3]}.jpg"
    if img.exists():
        L += [f"![{title}](images/{img.name})", ""]
    L += ["## Contents", "", "| ID | Level | Type | Act | Size |", "|---|---|---|---|---|"]
    for e in ls:
        anchor = re.sub(r"[^a-z0-9 -]", "", f"{e['id']} · {e['name']}".lower()).replace(" ", "-")
        L.append(f"| {e['id']} | [{esc(e['name'])}](#{anchor}) | {e['type']} | {esc(e['act'])} | {size_label(e['size'])} |")
    L += ["", "---", ""]
    for e in ls:
        L += [card(e, by_id), "---", ""]
    return "\n".join(L)


