def update_readme(levels):
    readme = OUT / "README.md"
    if not readme.exists():
        return
    text = readme.read_text(encoding="utf-8")
    a, b = "<!-- STATS:START -->", "<!-- STATS:END -->"
    if a not in text:
        return
    rows = [a, "| | Count |", "|---|---|"]
    for code, (title, _d) in GROUPS.items():
        rows.append(f"| {title} | {sum(1 for e in levels if e['group'] == code)} |")
    rows += [f"| **Levels total** | **{len(levels)}** |", f"| Modular kits | {len(KITS)} kits · {sum(len(k['pieces']) for k in KITS)} pieces |",
             f"| Metrics | {len(METRICS)} metrics · {len(NAV_AGENTS)} navigation agents · {len(GYM)} gym lanes |", b]
    readme.write_text(text[: text.index(a)] + "\n".join(rows) + text[text.index(b) + len(b):], encoding="utf-8")


def main():
    levels, problems = expand()
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    if "--check" in sys.argv:
        print(f"OK: {len(levels)} levels, {len(KITS)} kits")
        return
    by_id = {e["id"]: e for e in levels}
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "01-level-overview.md").write_text(overview_doc(levels) + "\n", encoding="utf-8")
    (OUT / "02-metrics-and-gym.md").write_text(metrics_doc() + "\n", encoding="utf-8")
    for code in GROUPS:
        extra = planets_intro(levels) if code == "PLN" else ""
        (OUT / GROUPS[code][1]).write_text(group_doc(code, levels, by_id, extra) + "\n", encoding="utf-8")
    (OUT / "10-modular-kits.md").write_text(kits_doc() + "\n", encoding="utf-8")
    (OUT / "11-space-travel-and-planet-transitions.md").write_text(travel_doc(levels) + "\n", encoding="utf-8")
    write_data(levels)
    update_readme(levels)
    print(f"Built {len(levels)} levels, {len(KITS)} kits ({sum(len(k['pieces']) for k in KITS)} pieces) -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
