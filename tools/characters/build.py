def swatches(palette):
    return " · ".join(f"{n} `{h}`" for n, h in palette)


GAMEPLAY_LABELS = {"hp": "HP", "speed_mps": "Speed (m/s)", "damage": "Damage", "infection_per_hit": "Infection / hit",
                   "counter": "Counter", "weapons": "Weapons", "behaviour": "Behavior", "phases": "Phases",
                   "talk_down": "Talk-down", "summons": "Summons", "attacks": "Attacks"}
MODULE_SHARE = [("pattern", 0.0), ("bod", 0.45), ("head", 0.2), ("leg", 0.2), ("wing", 0.15), ("tail", 0.1)]

VISUAL_LABELS = [("silhouette", "Silhouette"), ("face", "Face"), ("hair", "Hair"), ("body", "Body"), ("marks", "Marks"),
                 ("bloom", "Bloom growth"), ("weak_points", "Weak points"), ("phases", "Phases"), ("environment", "Environment"),
                 ("faction", "Faction"), ("face_visible", "Face visible"), ("fur", "Fur / feathers"),
                 ("props", "Signature props"), ("acting", "Acting & movement"), ("audio", "Audio")]


def visual_block(v):
    lines = []
    for key, label in VISUAL_LABELS:
        if v.get(key):
            val = v[key]
            if isinstance(val, list):
                val = "; ".join(val)
            lines.append(f"- **{label}:** {esc(val)}")
    if v.get("palette"):
        lines.append(f"- **Palette:** {swatches(v['palette'])}")
    return lines


def card(c, full=True):
    L = []
    title = f"### {c['id']} · {c['name']}" + (f" — *{c['title']}*" if c["title"] else "")
    L += [title, ""]
    meta = [f"`{c['registry_id']}`", f"**Tier** {c['tier']}", f"**Size** {c['size_label']}"]
    if c["age"] and c["age"] != "—":
        meta.append(f"**Age** {c['age']}")
    if c["pronouns"] and c["pronouns"] != "—":
        meta.append(f"**Pronouns** {c['pronouns']}")
    L += [" · ".join(meta), ""]
    if c["role"]:
        L += [f"> {esc(c['role'])}", ""]
    if c["appears"]:
        L += [f"**Appears:** {esc(c['appears'])}", ""]

    s = c["story"]
    if any(s.get(k) for k in ("want", "need", "wound", "lie")):
        L += ["**Story**", "", "| Want | Need | Wound | Lie |", "|---|---|---|---|",
              f"| {esc(s.get('want', '—'))} | {esc(s.get('need', '—'))} | {esc(s.get('wound', '—'))} | {esc(s.get('lie', '—'))} |", ""]
    if s.get("arc"):
        L += [f"**Arc:** {esc(s['arc'])}", ""]
    if c["voice"]:
        L += [f"**Voice & performance:** {esc(c['voice'])}", ""]

    gp = {k: v for k, v in c["gameplay"].items() if k != "role"}
    if gp:
        L += ["**Gameplay**", "", "| " + " | ".join(GAMEPLAY_LABELS.get(k, k.replace("_", " ").capitalize()) for k in gp) + " |",
              "|" + "---|" * len(gp), "| " + " | ".join(esc(v) for v in gp.values()) + " |", ""]

    vb = visual_block(c["visual"])
    if vb:
        L += ["**Visual design**", ""] + vb + [""]

    if c["customization"]:
        L += ["**Character creator**", "", "| Area | Options |", "|---|---|"]
        for k, v in c["customization"].items():
            L.append(f"| {k} | {esc(v)} |")
        L.append("")

    if c["outfits"]:
        L += ["**Wardrobe**", "", "| Outfit | When | Description | Pieces | Asset |", "|---|---|---|---|---|"]
        base = c["assets"][0]["asset"]
        for o in c["outfits"]:
            if o["shared"]:
                asset = f"`{o['shared']}` (shared suit)"
            elif o["key"] in NON_ASSET_OUTFITS:
                asset = "— (conversion / built from kits)"
            elif o["key"] == "Modules":
                asset = f"`{base}_<Module>_##`"
            else:
                asset = f"`{base}_Outfit_{o['key']}`"
            L.append(f"| **{esc(o['name'])}** | {esc(o['acts'])} | {esc(o['desc'])} | {esc(', '.join(o['pieces'])) or '—'} | {asset} |")
        L.append("")

    # Blender spec
    L += ["**Blender assets**", "", "| Asset | Type | Contents | LOD0 / 1 / 2 / 3 tris |", "|---|---|---|---|"]
    for a in c["assets"]:
        count = f" ×{a['count']}" if a["count"] > 1 else ""
        L.append(f"| `{a['asset']}`{count} | {a['kind']} | {esc(a['label'])} | {' / '.join(fmt(t) for t in a['lod_tris'])} |")
    L.append("")
    split = " · ".join(f"{k} {fmt(v)}" for k, v in c["budget_split"].items())
    L += ["**Blender spec**", ""]
    L.append(f"- **Skeleton:** {c['skeleton_label']} · {c['bone_count']} bones ({c['deform_bones']} deform)"
             + (f" · extra bones: {esc('; '.join(c['extra_bones']))}" if c["extra_bones"] else ""))
    L.append(f"- **Budget (LOD0 {fmt(TIERS[c['tier']]['tris'])} tris):** {split}")
    L.append(f"- **Textures:** {c['textures']}")
    shapes = f"{c['facial_set']} set ({c['facial_shapes']} shape keys, see chapter 10)"
    if c["extra_shapes"]:
        shapes += f" + {esc(', '.join(c['extra_shapes']))}"
    L.append(f"- **Facial rig:** {shapes}" + (" · **facial capture**" if c["facial_capture"] else ""))
    if c["infection"]:
        L.append("- **Infection states:** Stage 0–4 via `INF_` shape keys + infection masks (chapter 00 §0.10)")
    L.append(f"- **Skin weights:** max {c['influences']} influences per vertex")
    L.append(f"- **Hair:** {c['hair_spec']}" + (f" · {esc('; '.join(f'{h[1]} ({h[2]})' for h in c['hair']))}" if c["hair"] else ""))
    if c["cloth"]:
        L.append(f"- **Cloth / physics:** {esc(', '.join(c['cloth']))}")
    if c["sockets"]:
        L.append(f"- **Sockets:** " + ", ".join(f"`{s.split(' ')[0]}`" for s in c["sockets"]))
    if c["mocap"]:
        L.append(f"- **Capture:** {esc(c['mocap'])}")
    if c["notes"]:
        L.append(f"- **Notes:** {esc(c['notes'])}")
    L.append(f"- **Files:** `{c['assets'][0]['blend_path']}` (one .blend per asset)")
    L.append("")
    return "\n".join(L)


def group_doc(code, chars, intro, extra=""):
    _prefix, title, doc = GROUPS[code]
    number = doc.split("-", 1)[0]
    cs = [c for c in chars if c["group"] == code]
    n_assets = sum(a["count"] for c in cs for a in c["assets"] if a["kind"] != "Kit texture")
    L = [GENERATED_NOTE, f"# {number} — {title}", "", intro, "",
         f"**{len(cs)} entries · {n_assets} Blender assets.** Standards: [00 — Character Art & Blender Standards](00-character-art-standards.md) · "
         f"skeletons and facial sets: [10 — Skeletons, Rigging & Facial](10-skeletons-rigging-and-facial.md).", ""]
    L += ["## Contents", "", "| ID | Name | Tier | Size | Assets |", "|---|---|---|---|---|"]
    for c in cs:
        anchor = re.sub(r"[^a-z0-9 -]", "", f"{c['id']} · {c['name']}" .lower() + (f" — {c['title']}".lower() if c["title"] else "")).replace(" ", "-")
        L.append(f"| {c['id']} | [{c['name']}](#{anchor}) | {c['tier']} | {c['size_label']} | {sum(a['count'] for a in c['assets'] if a['kind'] != 'Kit texture')} |")
    L += ["", extra, "---", ""] if extra else ["", "---", ""]
    for c in cs:
        L += [card(c), "---", ""]
    return "\n".join(L)


