SUBSCRIPTS = str.maketrans("₀₁₂₃₄₅₆₇₈₉", "0123456789")


def pascal(text):
    text = text.translate(SUBSCRIPTS).replace("×", "x").replace("&", "And").replace("'", "").replace("’", "").replace('"', "")
    text = re.sub(r"\(.*?\)", lambda m: m.group(0)[1:-1], text)
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^0-9A-Za-z]+", text) if p)


def snake(text):
    text = text.translate(SUBSCRIPTS).replace('"', "").replace("'", "")
    return re.sub(r"[^0-9a-z]+", "_", text.lower()).strip("_")


def fmt(n):
    return f"{int(n):,}"


def lods(tris):
    return [0, 0, 0, 0] if not tris else [max(200, int(round(tris * r))) for r in LOD_RATIOS]


def esc(t):
    return str(t).replace("|", "\\|")


def skeleton_label(spec):
    name = SK.TEMPLATE_NAMES[spec["template"]]
    if spec["template"] == "humanoid":
        return f"{name}, {SK.PROFILES[spec.get('profile', 'adult_average')]['label'].lower()}"
    return name


def size_label(spec):
    t = spec["template"]
    if t == "humanoid":
        return f"{spec['height']:.2f} m tall"
    if t in ("quadruped", "hexapod", "flyer"):
        s = f"{spec['shoulder_h']:.2f} m at the shoulder, {spec['length']:.2f} m long"
        return s + (f", {spec['wings'] * 2:.2f} m wingspan" if spec.get("wings") else "")
    if t == "serpentine":
        return f"{spec['length']:.2f} m long"
    if t == "cetacean":
        return f"{spec['length']:.1f} m long, {spec['girth']:.1f} m girth"
    if t == "drone":
        return f"{spec['size']:.2f} m"
    if t == "hologram":
        return f"{spec['height']:.2f} m"
    return ""


def size_sort(spec):
    return spec.get("height") or spec.get("shoulder_h") or spec.get("length") or spec.get("size") or 0


# --------------------------------------------------------------------------- expand
def expand():
    problems, chars, seen = [], [], set()
    for c in CHARACTERS:
        prefix = GROUPS[c["group"]][0]
        base = f"SK_{prefix}_{pascal(c['key'].replace('_', ' ')) if c['key'] else pascal(c['name'])}"
        tier = TIERS[c["tier"]]
        bones = SK.build_skeleton(c["skeleton"])
        assets = []

        def add(name, kind, label, tris, notes="", count=1):
            if name in seen:
                problems.append(f"Duplicate asset {name}")
            seen.add(name)
            assets.append(OrderedDict(asset=name, kind=kind, label=label, lod_tris=lods(tris), count=count, notes=notes,
                                      blend_path=f"assets/characters/{GROUPS[c['group']][2][3:-3]}/{name.replace('_##', '')}.blend"))

        add(base, "Base", "Base body + head (default outfit and hair for budget checks)", tier["tris"],
            "Includes head, body skin and the default outfit and hair when checking the full-character budget.")
        body_budget = tier["split"].get("Body + outfit") or tier["split"].get("Body") or tier["tris"]
        hair_budget = tier["split"].get("Hair", 0)
        for o in c["outfits"]:
            if o["shared"]:
                continue
            if o["key"] == "Modules":
                for piece in o["pieces"]:
                    m = re.match(r"(.+?)\s*×\s*(\d+)", piece)
                    fam, n = (m.group(1), int(m.group(2))) if m else (piece, 1)
                    share = next((v for k, v in MODULE_SHARE if k in fam.lower()), 0.08)
                    if share == 0:
                        add(f"T_CRE_{pascal(c['key'] or c['name'])}_{pascal(fam)}_##", "Kit texture", f"{fam} (×{n}, 2K masks, no mesh)", 0, count=n)
                    else:
                        add(f"{base}_{pascal(fam)}_##", "Kit module", f"{fam} (×{n})", int(tier["tris"] * share), count=n)
                continue
            if o["key"] in NON_ASSET_OUTFITS:
                continue
            add(f"{base}_Outfit_{o['key']}", "Outfit", o["name"], body_budget, o["acts"])
        for key, label, kind in c["hair"]:
            if key == "Library":
                continue
            add(f"{base}_Hair_{key}", "Hair", f"{label} ({kind})", hair_budget or 4000)
        for vkey, vdesc in c["variants"]:
            add(f"{base}_{pascal(vkey)}", "Variant", vdesc, tier["tris"])
        if c["arms_1p"]:
            for o in c["outfits"]:
                if not o["shared"]:
                    add(f"{base}_Arms1P_{o['key']}", "1P arms", f"First-person arms — {o['name']}", 25000)
        facial = SK.FACIAL_SETS[tier["facial"]]
        if c["group"] == "HOL" and c["name"] == "Mimic":
            facial = SK.FACIAL_SETS["secondary"]
        humanoid = c["skeleton"]["template"] == "humanoid"
        entry = OrderedDict(
            id=c["id"], group=c["group"], group_name=GROUPS[c["group"]][1], key=c["key"] or snake(c["name"]),
            registry_id=f"char.{c['group'].lower()}.{c['key'] or snake(c['name'])}", name=c["name"], title=c["title"],
            tier=c["tier"], age=c["age"], pronouns=c["pronouns"], role=c["role"], appears=c["appears"], story=c["story"],
            voice=c["voice"], visual=c["visual"], outfits=c["outfits"], hair=c["hair"], variants=c["variants"],
            skeleton=c["skeleton"], skeleton_label=skeleton_label(c["skeleton"]), size_label=size_label(c["skeleton"]),
            bone_count=len(bones), deform_bones=sum(1 for b in bones if b["deform"]), extra_bones=c["extra_bones"],
            facial_set=tier["facial"] if not (c["group"] == "HOL" and c["name"] == "Mimic") else "secondary",
            facial_shapes=len(facial), extra_shapes=c["extra_shapes"],
            infection=c["infection"] and humanoid and c["tier"] not in ("Enemy", "Elite", "Boss", "Hologram"),
            facial_capture=c["facial_capture"], mocap=c["mocap"], cloth=c["cloth"], notes=c["notes"], gameplay=c["gameplay"],
            customization=c["customization"], arms_1p=c["arms_1p"], art_set=c["art"],
            sockets=([s[0] for s in SK.HUMANOID_SOCKETS] if humanoid else []) + [s for s in c["sockets"] if not s.split(" ")[0] in {x[0] for x in SK.HUMANOID_SOCKETS}],
            textures=tier["textures"], influences=tier["influences"], hair_spec=tier["hair"], budget_split=tier["split"],
            assets=assets,
        )
        chars.append(entry)
    return chars, problems


