def update_readme(chars, kit_total):
    readme = OUT / "README.md"
    if not readme.exists():
        return
    text = readme.read_text(encoding="utf-8")
    start, end = "<!-- STATS:START -->", "<!-- STATS:END -->"
    if start not in text:
        return
    n_assets = sum(a["count"] for c in chars for a in c["assets"] if a["kind"] != "Kit texture")
    rows = [start, "| | Count |", "|---|---|"]
    for code, (_p, title, _d) in GROUPS.items():
        cs = [c for c in chars if c["group"] == code]
        rows.append(f"| {title} | {len(cs)} {'entry' if len(cs) == 1 else 'entries'} · {sum(a['count'] for c in cs for a in c['assets'] if a['kind'] != 'Kit texture')} assets |")
    rows += [f"| Text-and-bark notables (kit-built) | {len(MORE_SURVIVORS)} (one signature piece each) |",
             f"| Procedural survivor kit | {kit_total} kit meshes |",
             f"| **Total Blender assets** | **{n_assets + len(MORE_SURVIVORS) + kit_total}** |", end]
    text = text[: text.index(start)] + "\n".join(rows) + text[text.index(end) + len(end):]
    readme.write_text(text, encoding="utf-8")


def main():
    chars, problems = expand()
    if problems:
        print("\n".join(problems))
        sys.exit(1)
    if "--check" in sys.argv:
        print(f"OK: {len(chars)} characters, {sum(a['count'] for c in chars for a in c['assets'] if a['kind'] != 'Kit texture')} assets")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "01-cast-overview.md").write_text(overview_doc(chars) + "\n", encoding="utf-8")
    for code in GROUPS:
        extra = notables_extra() if code == "NOT" else (portraits_extra() if code == "CST" else "")
        (OUT / GROUPS[code][2]).write_text(group_doc(code, chars, INTROS[code], extra) + "\n", encoding="utf-8")
    kit_md, kit_total = kit_doc()
    (OUT / "05-procedural-survivors.md").write_text(kit_md + "\n", encoding="utf-8")
    (OUT / "10-skeletons-rigging-and-facial.md").write_text(skeleton_doc() + "\n", encoding="utf-8")
    write_data(chars, kit_total)
    update_readme(chars, kit_total)
    print(f"Built {len(chars)} characters, {sum(a['count'] for c in chars for a in c['assets'] if a['kind'] != 'Kit texture')} assets "
          f"(+{len(MORE_SURVIVORS)} signature pieces, {kit_total} kit meshes) -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
