def write_csvs(parts):
    DATA.mkdir(parents=True, exist_ok=True)
    cols = ["asset", "part_id", "registry_id", "part_name", "variant", "category", "group", "grid", "size_cells_WxHxD",
            "dims_m_WxHxD", "tier", "art_set", "complexity", "mass_kg", "hp", "power_kw", "recipe",
            "lod0_tris", "lod1_tris", "lod2_tris", "lod3_tris", "build_stages", "collision_max_hulls",
            "texture_strategy", "texel_density_px_m", "mount_faces", "airtight_faces", "sockets", "moving_parts",
            "emissive", "debris_set", "blend_path", "export_path", "status", "owner", "notes"]
    with open(DATA / "art_tracker_parts.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(cols)
        for p in parts:
            for a in p["assets"]:
                w.writerow([
                    a["asset"], p["id"], p["registry_id"], p["name"], a["variant"] or "", p["category"], p["sub"], a["grid"],
                    fmt_size(a["size_cells"]), "x".join(f"{v:.2f}" for v in a["dims_m"]), a["tier"], p["art_set"],
                    p["complexity"], a["mass_kg"], a["hp"], a["power_kw"] or 0,
                    "; ".join(f"{k}:{v}" for k, v in a["recipe"].items()),
                    *a["lod_tris"], p["build_stages"], p["collision_max_hulls"],
                    S.COMPLEXITY[p["complexity"]]["texture"], a["texel_density_px_per_m"],
                    " ".join(p["mount_faces"]), " ".join(p["airtight_faces"]),
                    " ".join(socket_names(p["sockets"])), " | ".join(p["moving_parts"]),
                    " | ".join(p["emissive"]), a["debris_set"], a["blend_path"], a["export_path"],
                    "Not started", "", p["modeling_notes"],
                ])
    with open(DATA / "art_tracker_props.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["asset", "item_id", "name", "type", "tier", "dims_m", "tris_lod0_or_1p", "tris_3p", "textures", "status", "owner", "notes"])
        for c in COMPONENTS:
            w.writerow([f"SM_CMP_{pascal(c['name'])}", c["id"], c["name"], "Component", c["tier"],
                        "x".join(f"{v:.2f}" for v in c["dims_m"]), c["tris"], "", "512 / prop atlas", "Not started", "", c["look"]])
        for c in RESOURCES:
            w.writerow([f"SM_RES_{pascal(c['name'])}", c["id"], c["name"], c["kind"].title(), c["tier"],
                        "x".join(f"{v:.2f}" for v in c["dims_m"]), c["tris"], "", "512 / prop atlas", "Not started", "", c["look"]])
        for e in EQUIPMENT:
            if e["kind"] == "Suit":
                name = f"SK_SUIT_{pascal(e['name'])}"
            elif e["kind"] in ("Suit Module", "Drone"):
                name = f"SK_EQP_{pascal(e['name'])}" if e["bones"] else f"SM_EQP_{pascal(e['name'])}"
            else:
                name = f"SK_EQP_{pascal(e['name'])}_1P + SM_EQP_{pascal(e['name'])}_3P"
            w.writerow([name, e["id"], e["name"], e["kind"], e["tier"], "x".join(f"{v:.2f}" for v in e["dims_m"]),
                        e["tris_1p"] or "", e["tris_3p"] or "", e["tex"], "Not started", "", e["notes"]])


def write_json(parts):
    DATA.mkdir(parents=True, exist_ok=True)
    standards = {
        "cell_m": S.CELL_M,
        "texel_density_px_per_m": S.TEXEL_DENSITY,
        "complexity": S.COMPLEXITY,
        "lod_ratios": S.LOD_RATIOS,
        "lod_screen_size": S.LOD_SCREEN_SIZE,
        "lod_min_tris": S.LOD_MIN_TRIS,
        "build_stage_names": {str(k): v for k, v in S.BUILD_STAGE_NAMES.items()},
        "art_sets": S.ART_SETS,
        "faces": S.FACES,
        "socket_types": S.SOCKET_TYPES,
        "categories": {k: {"key": v[0], "name": v[1], "doc": v[2]} for k, v in S.CATEGORIES.items()},
        "axes": {"front": "+X", "up": "+Z", "left": "+Y", "units": "metres, unit scale 1.0"},
    }
    payload = OrderedDict(schema="exodus.parts/1", standards=standards, parts=parts)
    (DATA / "parts.json").write_text(json.dumps(payload, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    (DATA / "components.json").write_text(json.dumps(
        {"schema": "exodus.items/1", "components": COMPONENTS, "resources": RESOURCES}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    (DATA / "equipment.json").write_text(json.dumps(
        {"schema": "exodus.equipment/1", "equipment": EQUIPMENT}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def update_readme_stats(parts):
    readme = OUT / "README.md"
    if not readme.exists():
        return
    text = readme.read_text(encoding="utf-8")
    start, end = "<!-- STATS:START -->", "<!-- STATS:END -->"
    if start not in text or end not in text:
        return
    total_assets = sum(len(p["assets"]) for p in parts)
    lg = sum(1 for p in parts for a in p["assets"] if a["grid"] == "LG")
    sg = total_assets - lg
    n_equip_assets = sum(2 if e["kind"] not in ("Suit", "Suit Module", "Drone") else 1 for e in EQUIPMENT)
    stats = "\n".join([
        start,
        "| | Count |",
        "|---|---|",
        f"| Buildable parts | **{len(parts)}** across {len(S.CATEGORIES)} categories |",
        f"| Block assets (per grid × variant) | **{total_assets}** ({lg} large grid, {sg} small grid) |",
        f"| Components | {len(COMPONENTS)} |",
        f"| Resources, ingots & fuels | {len(RESOURCES)} |",
        f"| Handheld equipment, suits, modules & drones | {len(EQUIPMENT)} items ({n_equip_assets} assets) |",
        f"| **Total Blender assets** | **{total_assets + len(COMPONENTS) + len(RESOURCES) + n_equip_assets}** |",
        end,
    ])
    text = text[: text.index(start)] + stats + text[text.index(end) + len(end):]
    readme.write_text(text, encoding="utf-8")


def main():
    parts, problems = expand()
    if problems:
        print("Catalog problems:")
        for p in problems:
            print("  -", p)
        sys.exit(1)
    if "--check" in sys.argv:
        print(f"OK: {len(parts)} parts, {sum(len(p['assets']) for p in parts)} assets")
        return
    OUT.mkdir(parents=True, exist_ok=True)
    write_json(parts)
    write_csvs(parts)
    (OUT / "01-master-parts-list.md").write_text(master_doc(parts) + "\n", encoding="utf-8")
    for code, (_k, _n, doc) in S.CATEGORIES.items():
        (OUT / doc).write_text(category_doc(code, parts) + "\n", encoding="utf-8")
    (OUT / "17-components-and-resources.md").write_text(components_doc(parts) + "\n", encoding="utf-8")
    (OUT / "18-handheld-equipment-and-suits.md").write_text(equipment_doc() + "\n", encoding="utf-8")
    update_readme_stats(parts)
    total = sum(len(p["assets"]) for p in parts)
    print(f"Built {len(parts)} parts / {total} block assets, {len(COMPONENTS)} components, "
          f"{len(RESOURCES)} resources, {len(EQUIPMENT)} equipment items -> {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
